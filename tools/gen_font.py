def main() -> None:
    table = {c: [0] * 7 for c in range(32, 128)}
    for line in GLYPHS.strip().splitlines():
        key, *rows = line.split()
        ch = 127 if key == r"\x7f" else ord(key)
        if len(rows) != 7 or any(len(r) != 5 for r in rows):
            raise SystemExit(f"glifo mal formado: {line!r}")
        table[ch] = [sum((1 << (4 - i)) for i, p in enumerate(r) if p == "#") for r in rows]
    out = ["// GENERADO por tools/gen_font.py - no editar a mano.",
           "#pragma once", "#include <stdint.h>", "",
           "// 96 glifos (ASCII 32..127), 7 filas de 5 bits; bit 4 = columna izquierda.",
           "static const uint8_t kFont5x7[96][7] = {"]
    for c in range(32, 128):
        rows = ",".join(f"0x{v:02X}" for v in table[c])
        label = "deg" if c == 127 else ("sp" if c == 32 else chr(c).replace("\\", "bs"))
        out.append(f"    {{{rows}}},  // {label}")
    out.append("};")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out) + "\n")
    print(f"OK: {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
